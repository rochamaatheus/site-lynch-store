const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const {chromium} = require('playwright');
const base = process.env.QA_URL || 'http://localhost:8000';
if (!/^http:\/\/(localhost|127\.0\.0\.1):/.test(base)) throw new Error('QA permitido somente em ambiente local.');
const results = [];
const pass = text => results.push(text);
(async () => {
  const browser = await chromium.launch({channel:'chrome',headless:true});
  const ctx = await browser.newContext({viewport:{width:390,height:844}});
  const page = await ctx.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const go = route => page.goto(base + route);
  const csrf = async () => page.locator('input[name=csrf]').last().inputValue();
  const post = async (route, data) => ctx.request.post(base+route,{form:{csrf:await csrf(),...data},maxRedirects:0});
  const login = async credentials => {
    await go('/admin/login.php');
    await page.locator('[name=username]').fill(credentials.username);
    await page.locator('[name=password]').fill(credentials.password);
    await Promise.all([page.waitForURL('**/admin/index.php'),page.getByRole('button',{name:'Entrar',exact:true}).click()]);
  };
  const creds = JSON.parse(fs.readFileSync(path.join(__dirname,'../.qa-credentials.json')));
  try {
    await go('/');
    await page.getByRole('button',{name:'Abrir menu',exact:true}).click();
    assert.equal(await page.locator('[data-drawer]').evaluate(e=>e.inert),false);
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('[data-drawer]').evaluate(e=>e.inert),true);
    pass('Menu mobile abre, fecha com Escape e restaura foco');
    await page.locator('#busca-mobile').fill('cosplay');
    await page.locator('.mobile-search button').click();
    assert.match(page.url(),/busca=cosplay/);
    assert.ok(await page.locator('.product-grid .card').count());
    pass('Busca mobile retorna produtos');
    const unauth = await ctx.request.get(base+'/admin/importar.php',{maxRedirects:0});
    assert.equal(unauth.status(),302);
    for (const route of ['/.env','/.env.test.local','/db/schema.sql','/includes/config.php','/vendor/autoload.php','/admin/partials/admin-header.php','/docs/explain.json']) {
      assert.equal((await ctx.request.get(base+route)).status(),403);
    }
    pass('Admin e arquivos internos protegidos');
    assert.equal((await ctx.request.get(base+'/produto.php?slug=inexistente')).status(),404);
    assert.equal((await ctx.request.get(base+'/nao-existe')).status(),404);
    assert.equal((await ctx.request.get(base+'/finalizar.php')).status(),405);
    const xml = await (await ctx.request.get(base+'/sitemap.xml')).text();
    assert.match(xml,/<urlset/);
    assert.ok((xml.match(/<loc>/g)||[]).length>=51);
    pass('404 real, método de checkout e sitemap verificados');
    await login(creds);
    pass('Login real no painel');
    await page.screenshot({path:'docs/qa-dashboard-mobile.png'});
    const suffix = Date.now().toString(36);
    await go('/admin/categorias.php');
    await page.locator('[name=name]').fill('QA '+suffix);
    await page.getByRole('button',{name:'Criar categoria',exact:true}).click();
    assert.match(await page.locator('main').innerText(),/cadastrad|criada/i);
    pass('Categoria criada pelo formulário');
    await go('/admin/produto-form.php');
    await page.locator('[name=name]').fill('Produto QA '+suffix);
    await page.locator('[name=slug]').fill('produto-qa-'+suffix);
    await page.locator('[name=short_description]').fill('Peça de teste automatizado');
    await page.locator('[name=description]').fill('Descrição com medidas de teste.');
    await page.locator('[name=category_id]').selectOption({label:'QA '+suffix});
    await page.locator('[name=price_on_request]').uncheck();
    await page.locator('[name=price]').fill('129,90');
    await page.locator('[name=availability][value=pronta_entrega]').check();
    await page.getByRole('button',{name:'Salvar e cadastrar fotos',exact:true}).click();
    assert.match(page.url(),/produto-imagens.php\?id=/);
    const productId = new URL(page.url()).searchParams.get('id');
    await page.locator('input[type=file]').setInputFiles(path.join(__dirname,'fixtures/upload.png'));
    await page.getByRole('button',{name:'Enviar fotos',exact:true}).click();
    assert.ok(await page.locator('img').count()>0);
    assert.doesNotMatch(await page.locator('main').innerText(),/Falha|Fatal error/);
    pass('Produto cadastrado com preço, categoria e upload de imagem');
    await go('/produto.php?slug=produto-qa-'+suffix);
    assert.match(await page.locator('h1').innerText(),/Produto QA/);
    assert.match(await page.locator('.pinfo').innerText(),/129,90/);
    await page.getByRole('button',{name:'Adicionar ao carrinho',exact:true}).click();
    await go('/carrinho.php');
    assert.ok(await page.locator('[name=qty]').count());
    await page.locator('[name=qty]').fill('3');
    await Promise.all([page.waitForEvent('load'), page.locator('[name=qty]').press('Tab')]);
    assert.match(await page.locator('main').innerText(),/389,70/);
    const invalidCsrf = await ctx.request.post(base+'/carrinho.php',{form:{action:'clear',csrf:'invalid'},maxRedirects:0});
    assert.equal(invalidCsrf.status(),303);
    await go('/carrinho.php');
    assert.match(await page.locator('main').innerText(),/Produto QA/);
    pass('Carrinho calcula 3 unidades e rejeita alteração sem CSRF');
    await go('/admin/importar.php');
    const csv = 'nome;slug;categoria;preco;disponibilidade;descricao_curta;descricao;ativo;destaque\nImportado QA '+suffix+';importado-qa-'+suffix+';QA '+suffix+';79,90;pronta_entrega;Resumo;Detalhes;0;0\n';
    await page.locator('[name=sheet]').setInputFiles({name:'catalogo.csv',mimeType:'text/csv',buffer:Buffer.from(csv)});
    await page.getByRole('button',{name:'Conferir planilha',exact:true}).click();
    assert.match(await page.locator('main').innerText(),/Nenhum produto foi alterado/);
    await page.getByRole('button',{name:/Confirmar importação/}).click();
    assert.match(await page.locator('main').innerText(),/1 produtos criados/);
    await go('/admin/importar.php');
    await page.locator('[name=sheet]').setInputFiles(path.join(__dirname,'fixtures/import.xlsx'));
    await page.locator('[name=mode]').selectOption('upsert');
    await page.getByRole('button',{name:'Conferir planilha',exact:true}).click();
    await page.getByRole('button',{name:/Confirmar importação/}).click();
    assert.match(await page.locator('main').innerText(),/1 atualizados/);
    pass('Importações CSV e XLSX confirmadas pela interface');
    const exported = await ctx.request.get(base+'/admin/exportar.php');
    assert.match(exported.headers()['content-type'],/text\/csv/);
    assert.match(await exported.text(),/importado-qa-/);
    pass('Exportação de catálogo com dados reais');

    await go('/admin/configuracoes.php');
    const settings = await page.locator('input[name],textarea[name]').evaluateAll(nodes=>Object.fromEntries(nodes.filter(e=>!['csrf','hero_banner'].includes(e.name)).map(e=>[e.name,e.value])));
    await post('/admin/configuracoes.php',{...settings,whatsapp_number:'5511999999999'});
    await go('/carrinho.php');
    const checkout = await post('/finalizar.php',{});
    assert.equal(checkout.status(),303);
    const location = checkout.headers().location;
    assert.match(location,/^https:\/\/wa.me\/5511999999999/);
    assert.match(decodeURIComponent(location),/Pedido #\d+/);
    const again = await post('/finalizar.php',{});
    assert.equal(again.headers().location,location);
    await go('/carrinho.php');
    assert.match(await page.locator('main').innerText(),/Produto QA/);
    pass('Checkout prepara URL, evita duplicidade e mantém carrinho; nenhuma mensagem enviada');
    const orderId = decodeURIComponent(location).match(/Pedido #(\d+)/)[1];
    await go('/admin/pedidos.php?id='+orderId);
    await page.locator('[name=status]').selectOption('em_atendimento');
    await page.locator('[name=notes]').fill('QA: atendimento de teste');
    await page.getByRole('button',{name:'Salvar atendimento',exact:true}).click();
    assert.equal(await page.locator('[name=status]').inputValue(),'em_atendimento');
    pass('Pedido localizado e situação atualizada');
    await go('/admin/configuracoes.php');
    await post('/admin/configuracoes.php',settings);
    await go('/admin/produto-form.php?id='+productId);
    await post('/admin/produto-excluir.php',{id:productId,action:'delete'});
    assert.equal((await ctx.request.get(base+'/produto.php?slug=produto-qa-'+suffix)).status(),404);
    pass('Desativação retira produto da loja');

    const pages = ['/','/produto.php?slug=peca-de-cosplay-01','/carrinho.php','/admin/index.php','/admin/produtos.php','/admin/importar.php','/admin/pedidos.php','/admin/configuracoes.php','/admin/conta.php'];
    const axeIssues = [];
    for (const width of [320,390,768,1440]) {
      await page.setViewportSize({width,height:900});
      for (const route of pages) {
        await go(route);
        const overflow = await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1);
        assert.equal(overflow,false,'Overflow '+width+' '+route);
        if (width===390) {
          // Injeta o axe por avaliacao direta: a CSP do site (script-src 'self') bloqueia <script> inline, e queremos manter assim.
          await page.evaluate(fs.readFileSync(require.resolve('axe-core/axe.min.js'),'utf8'));
          const scan = await page.evaluate(async()=>await axe.run(document,{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa']}}));
          if (scan.violations.length) axeIssues.push({route,violations:scan.violations.map(v=>({id:v.id,impact:v.impact,nodes:v.nodes.map(n=>n.target)}))});
        }
      }
    }
    fs.writeFileSync('docs/accessibility-tests.json',JSON.stringify(axeIssues,null,2));
    assert.deepEqual(axeIssues,[],'Violações WCAG');
    pass('9 páginas sem overflow em 320, 390, 768 e 1440px e sem violações axe WCAG');
    await page.setViewportSize({width:390,height:844});
    await go('/'); await page.screenshot({path:'docs/qa-home-mobile.png'});
    await go('/produto.php?slug=peca-de-cosplay-01'); await page.screenshot({path:'docs/qa-product-mobile.png'});
    await go('/admin/importar.php'); await page.screenshot({path:'docs/qa-import-mobile.png'});
    const another = await browser.newContext();
    const otherPage = await another.newPage();
    await otherPage.goto(base+'/admin/login.php');
    await otherPage.locator('[name=username]').fill(creds.username);
    await otherPage.locator('[name=password]').fill(creds.password);
    await otherPage.getByRole('button',{name:'Entrar',exact:true}).click();
    await go('/admin/conta.php');
    const newPassword = creds.password + 'A';
    await page.locator('[name=current_password]').fill(creds.password);
    await page.locator('[name=password]').fill(newPassword);
    await page.locator('[name=confirm_password]').fill(newPassword);
    await page.getByRole('button',{name:'Alterar senha',exact:true}).click();
    await otherPage.goto(base+'/admin/index.php');
    assert.match(otherPage.url(),/login.php/);
    fs.writeFileSync(path.join(__dirname,'../.qa-credentials.json'),JSON.stringify({...creds,password:newPassword}));
    pass('Troca de senha invalida outra sessão já autenticada');
    await page.getByRole('button',{name:'Sair',exact:true}).click();
    assert.match(page.url(),/login.php/);
    pass('Logout por POST encerra sessão');
    assert.deepEqual(errors,[]);
    pass('Nenhum erro JavaScript nos fluxos exercitados');
    fs.writeFileSync('docs/browser-tests.json',JSON.stringify({passed:results,count:results.length,at:new Date().toISOString()},null,2));
    console.log(JSON.stringify({passed:results,count:results.length},null,2));
    await another.close();
  } catch (error) {
    fs.writeFileSync('docs/browser-tests.json',JSON.stringify({passed:results,error:error.message,url:page.url()},null,2));
    await page.screenshot({path:'docs/qa-failure.png',fullPage:true});
    throw error;
  } finally { await browser.close(); }
})().catch(error=>{console.error(error);process.exit(1)});
